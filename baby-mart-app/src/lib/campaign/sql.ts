/** Competitor price gap on the promoted category: the campaign window vs the four
 *  weeks before. Positive gap = Baby Mart dearer. */
export const SQL_COMPETITOR_MOVE = `
WITH c AS (SELECT START_DATE, COALESCE(SIMULATED_THROUGH, END_DATE) AS THRU, PROMOTED_CATEGORY FROM ${S}.CAMPAIGN WHERE CAMPAIGN_ID = ?)
SELECT IFF(d.CALENDAR_DATE >= c.START_DATE, 'During campaign', 'Four weeks before') AS PERIOD,
       ROUND(AVG(cp.PRICE_GAP_PCT), 2) AS AVG_GAP_PCT, COUNT(*) AS OBSERVATIONS
FROM BABY_MART_DEMO.CURATED.FACT_COMPETITOR_PRICING cp
JOIN BABY_MART_DEMO.CURATED.DIM_DATE d ON d.DATE_KEY = cp.DATE_KEY
JOIN BABY_MART_DEMO.CURATED.DIM_PRODUCT p ON p.PRODUCT_KEY = cp.PRODUCT_KEY
CROSS JOIN c
WHERE (c.PROMOTED_CATEGORY IS NULL OR p.CATEGORY = c.PROMOTED_CATEGORY)
  AND d.CALENDAR_DATE BETWEEN DATEADD('day', -28, c.START_DATE) AND c.THRU
GROUP BY 1 ORDER BY 1 DESC`;

