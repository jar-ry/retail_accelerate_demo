/** Cumulative conversion rate by day for each arm. */
export const SQL_DAILY = `
WITH first_conv AS (
  SELECT CUSTOMER_KEY, GROUP_CODE, MIN(EVENT_DATE) AS D FROM ${S}.CAMPAIGN_EVENT
  WHERE CAMPAIGN_ID = ? AND EVENT_TYPE = 'CONVERT' GROUP BY 1, 2
), n AS (
  SELECT GROUP_CODE, COUNT(*) AS N FROM ${S}.AUDIENCE_MEMBER WHERE CAMPAIGN_ID = ? GROUP BY 1
), daily AS (
  SELECT D, GROUP_CODE, COUNT(*) AS CONV FROM first_conv GROUP BY 1, 2
)
SELECT d.D AS EVENT_DATE, d.GROUP_CODE,
       SUM(d.CONV) OVER (PARTITION BY d.GROUP_CODE ORDER BY d.D) / MAX(n.N) OVER (PARTITION BY d.GROUP_CODE) AS CUM_RATE
FROM daily d JOIN n ON n.GROUP_CODE = d.GROUP_CODE
ORDER BY 1, 2`;

