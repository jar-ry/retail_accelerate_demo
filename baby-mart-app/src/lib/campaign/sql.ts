/** Lift by every dimension the investigator and the learnings read. Variant is
 *  left out: a holdout gets no variant, so variants are compared treated vs
 *  treated (SQL_VARIANTS_AB). */
export const SQL_LIFT_BY = `
WITH conv AS (
  SELECT DISTINCT CUSTOMER_KEY FROM ${S}.CAMPAIGN_EVENT WHERE CAMPAIGN_ID = ? AND EVENT_TYPE = 'CONVERT'
), mm AS (
  SELECT am.*, cv.CUSTOMER_KEY IS NOT NULL AS CONVERTED,
         IFF(COALESCE(am.NEG_VOICE_120D, 0) > 0 AND am.NEG_THEME IN ('Price and value', 'Promotions and offers'), 'Yes', 'No') AS GRIEVANCE
  FROM ${S}.AUDIENCE_MEMBER am LEFT JOIN conv cv ON cv.CUSTOMER_KEY = am.CUSTOMER_KEY
  WHERE am.CAMPAIGN_ID = ?
), d AS (
  SELECT 'Channel' AS DIM, CHANNEL_CODE AS VAL, GROUP_CODE, CONVERTED FROM mm
  UNION ALL SELECT 'Home state', HOME_STATE, GROUP_CODE, CONVERTED FROM mm
  UNION ALL SELECT 'Last purchase', RECENCY_BAND, GROUP_CODE, CONVERTED FROM mm
  UNION ALL SELECT 'Segment', SEGMENT_NAME, GROUP_CODE, CONVERTED FROM mm
  UNION ALL SELECT 'Child stage', CHILD_STAGE, GROUP_CODE, CONVERTED FROM mm
  UNION ALL SELECT 'Loyalty tier', LOYALTY_TIER, GROUP_CODE, CONVERTED FROM mm
  UNION ALL SELECT 'Needs the product', IFF(COALESCE(IS_RELEVANT, FALSE), 'Yes', 'No'), GROUP_CODE, CONVERTED FROM mm
  UNION ALL SELECT 'Home store short of promoted brand', IFF(COALESCE(STOCK_CONFLICT, FALSE), 'Yes', 'No'), GROUP_CODE, CONVERTED FROM mm
  UNION ALL SELECT 'Recent price complaint', GRIEVANCE, GROUP_CODE, CONVERTED FROM mm
  UNION ALL SELECT 'Uplift quadrant', UPLIFT_QUADRANT, GROUP_CODE, CONVERTED FROM mm WHERE UPLIFT_QUADRANT IS NOT NULL
)
SELECT DIM, COALESCE(VAL, 'Unknown') AS VAL,
       COUNT_IF(GROUP_CODE = 'TREATED') AS TN, COUNT_IF(GROUP_CODE = 'TREATED' AND CONVERTED) AS TC,
       COUNT_IF(GROUP_CODE = 'HOLDOUT') AS HN, COUNT_IF(GROUP_CODE = 'HOLDOUT' AND CONVERTED) AS HC
FROM d GROUP BY 1, 2 ORDER BY 1, 2`;

