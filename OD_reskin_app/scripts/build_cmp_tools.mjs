// Builds sql/od_45_procs.sql: the agents' procedure tools, each a
// JavaScript stored procedure embedding the app's own campaign code (see
// src/lib/campaign/tools.ts). Run after changing anything tools.ts imports:
//
//   node scripts/build_cmp_tools.mjs
//
// The schema module is replaced with the canonical name, ONEDIGITAL_DEMO.CAMPAIGN,
// which scripts/od_target.py rewrites per account like every other SQL file;
// the database helpers are replaced with a stub that throws, because no tool may
// reach them (they are async and the procedures are not).

import { build } from "esbuild";
import { readFileSync, writeFileSync } from "fs";
import path from "path";
import { fileURLToPath } from "url";

const app = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const stubs = {
  schema: `export const S = "ONEDIGITAL_DEMO.CAMPAIGN";`,
  db: `const no = () => { throw new Error("database helpers are not available inside a procedure"); };
export const q = no, batch = no, tx = no; export const NOW = ""; export class CmpError extends Error {}`,
};

const result = await build({
  entryPoints: [path.join(app, "src/lib/campaign/tools-entry.ts")],
  bundle: true,
  format: "iife",
  globalName: "CMPTOOLS",
  platform: "neutral",
  target: "es2019",
  write: false,
  legalComments: "none",
  plugins: [{
    name: "stubs",
    setup(b) {
      b.onResolve({ filter: /^\.\/(schema|db)$/ }, (a) => (a.importer.includes(`${path.sep}campaign${path.sep}`) ? { path: a.path.slice(2), namespace: "stub" } : undefined));
      b.onResolve({ filter: /^@\/lib\/snowflake$/ }, () => ({ path: "snowflake", namespace: "stub" }));
      b.onResolve({ filter: /^@\// }, (a) => ({ path: path.join(app, "src", a.path.slice(2)) + ".ts" }));
      b.onLoad({ filter: /.*/, namespace: "stub" }, (a) => ({ contents: stubs[a.path] ?? `export const DB = "ONEDIGITAL_DEMO";`, loader: "ts" }));
    },
  }],
});
const js = result.outputFiles[0].text;
if (js.includes("$$")) throw new Error("The bundle contains $$, which would end the procedure body.");

// A procedure tool on a warehouse cannot take an object argument, so specs and
// briefs arrive as JSON text (the tools parse either). The VARIANT signatures
// of an earlier build are dropped so a CALL never resolves to them.
const procs = [
  ["FIND_OPPORTUNITIES", "FOCUS VARCHAR", "CMPTOOLS.findOpportunities()",
    "Every candidate Officeworks play sized and valued like the audience builder, ranked by expected incremental margin, with the Bunnings and Kmart signals and school start dates."],
  ["SIZE_AUDIENCE", "SPEC VARCHAR", "CMPTOOLS.sizeAudience(SPEC)",
    "Size an audience spec exactly as the Audience builder does: funnel, suppressions, uplift quadrants, health and composition."],
  ["CHECK_CAMPAIGN_GUARDRAILS", "CATEGORY VARCHAR, BRAND VARCHAR, START_DATE VARCHAR, END_DATE VARCHAR", "CMPTOOLS.checkGuardrails(CATEGORY, BRAND, START_DATE, END_DATE)",
    "Stock shortfalls, overlapping campaigns, contact fatigue, school timing, the data-sharing rule, active offers and rejected ideas for a planned campaign."],
  ["ESTIMATE_LIFT", "CATEGORY VARCHAR, CHANNELS VARCHAR, NEED_STATE VARCHAR", "CMPTOOLS.estimateLift(CATEGORY, CHANNELS, NEED_STATE)",
    "Expected lift from comparable measured campaigns, with confidence intervals, lift by channel and uplift cells by need state."],
  ["CREATE_CAMPAIGN_DRAFT", "BRIEF VARCHAR, SPEC VARCHAR, RUN_ID VARCHAR", "CMPTOOLS.createDraft(BRIEF, SPEC, RUN_ID)",
    "Create a campaign BRIEF and a DRAFT audience from a validated spec. Never locks, approves or launches."],
  ["CAMPAIGN_EVIDENCE", "CAMPAIGN_ID VARCHAR", "CMPTOOLS.campaignEvidence(CAMPAIGN_ID)",
    "Everything an investigation needs about one campaign: lift and CI, alerts, lift by every targeting dimension, creative A/B, stock and overlapping campaigns."],
  ["TEST_HYPOTHESIS", "CAMPAIGN_ID VARCHAR, DIMENSION VARCHAR", "CMPTOOLS.testHypothesis(CAMPAIGN_ID, DIMENSION)",
    "Does a campaign's lift differ across one split (need state, business starter, school signal, channel, cold contact...)? Two-proportion test on the lift difference."],
];

const header = `-- ============================================================
-- OneDigital Campaign Manager — the agents' procedure tools (GENERATED)
--
-- Generated by scripts/build_cmp_tools.mjs from src/lib/campaign/tools.ts and the
-- modules it imports (spec, audience compiler, measurement, queries). Do not edit
-- by hand: change the TypeScript and rebuild. Each procedure embeds the same
-- bundle, so an agent's audience or lift is computed by the code the app runs.
-- Owner's rights: the agents run as the app's role, and every input is
-- validated in the bundle before it reaches SQL, where values are bound.
-- ============================================================

USE ROLE ACCOUNTADMIN;
USE WAREHOUSE OD_WH;
USE SCHEMA ONEDIGITAL_DEMO.CAMPAIGN;
`;

const body = procs.map(([name, args, call, comment]) => `
CREATE OR REPLACE PROCEDURE ${name}(${args})
RETURNS VARCHAR
LANGUAGE JAVASCRIPT
COMMENT = '${comment.replace(/'/g, "''")}'
EXECUTE AS OWNER
AS
$$
${js}
return ${call};
$$;
`).join("");

const out = path.join(app, "sql/od_45_procs.sql");
writeFileSync(out, header + body);
console.log(`wrote ${out}: ${procs.length} procedures, bundle ${(js.length / 1024).toFixed(0)} KB`);

// The agents' SizeAudience description lists exactly the fields the validator
// accepts, read from config.ts rather than copied.
const cfg = await build({ entryPoints: [path.join(app, "src/lib/campaign/config.ts")], bundle: true, format: "esm", write: false, platform: "neutral" });
const { FIELDS } = await import(`data:text/javascript;base64,${Buffer.from(cfg.outputFiles[0].text).toString("base64")}`);
const catalogue = Object.entries(FIELDS).map(([k, f]) =>
  `        - ${k} (${f.kind === "enum" ? `list: ${f.options.join(" | ")}` : f.kind === "bool" ? "yes/no" : "number"}): ${f.label}${f.hint ? `. ${f.hint}` : ""}`).join("\n");
const tmpl = readFileSync(path.join(app, "agent/deploy_od_campaign_agents.template.sql"), "utf8");
const agentSql = tmpl.replace("{{FIELD_CATALOGUE}}", catalogue)
  .replace("-- GENERATED from agent/deploy_od_campaign_agents.template.sql", "-- GENERATED -- do not edit. Source: agent/deploy_od_campaign_agents.template.sql");
if (agentSql.includes("{{")) throw new Error("Unfilled placeholder in the agent template.");
writeFileSync(path.join(app, "agent/deploy_od_campaign_agents.sql"), agentSql);
console.log(`wrote agent/deploy_od_campaign_agents.sql: ${Object.keys(FIELDS).length} audience fields`);
