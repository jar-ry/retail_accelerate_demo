// ─── OneDigital Campaign Manager: the reads behind every page ────────────────
//
// Every page loads from these. They read the CAMPAIGN schema's tables and views
// (od_40-44) and compute measurement here, in one place, so the rules hold on
// every surface:
//   - Lift is treated rate minus holdout rate. Rates are rebuilt from counts,
//     never averaged across rows or campaigns.
//   - A conversion is a member who bought in the campaign window, treated or held
//     out. Never conversions over clicks.
//   - "Today" is CMP_AS_OF() (13 Nov 2026), never CURRENT_DATE().
//
// Each query is an `export const SQL_* = \`...\`` interpolating only ${S}, so a
// gate script can run every one as written; BINDS gives representative values.

