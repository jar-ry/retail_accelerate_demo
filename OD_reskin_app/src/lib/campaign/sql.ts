// ─── Campaign measurement ────────────────────────────────────────────────────
// One row per campaign: both arms, the funnel over treated members, money.
export const SQL_CAMPAIGN_METRICS = `
WITH m AS (
  SELECT CAMPAIGN_ID, COUNT_IF(GROUP_CODE = 'TREATED') AS TREATED_N, COUNT_IF(GROUP_CODE = 'HOLDOUT') AS HOLDOUT_N,
         COUNT_IF(GROUP_CODE = 'TREATED' AND COALESCE(STOCK_CONFLICT, FALSE)) AS STOCK_CONFLICT_N,
         COUNT_IF(GROUP_CODE = 'TREATED' AND COALESCE(COLD_CONTACT, FALSE)) AS COLD_N
  FROM ${S}.AUDIENCE_MEMBER GROUP BY CAMPAIGN_ID
), e AS (
  SELECT CAMPAIGN_ID,
         COUNT(DISTINCT IFF(EVENT_TYPE = 'CONVERT' AND GROUP_CODE = 'TREATED', CUSTOMER_KEY, NULL)) AS T_CONV,
         COUNT(DISTINCT IFF(EVENT_TYPE = 'CONVERT' AND GROUP_CODE = 'HOLDOUT', CUSTOMER_KEY, NULL)) AS H_CONV,
         SUM(IFF(EVENT_TYPE = 'CONVERT' AND GROUP_CODE = 'TREATED', ORDER_VALUE_AUD, 0)) AS T_REVENUE,
         SUM(IFF(EVENT_TYPE = 'CONVERT' AND GROUP_CODE = 'HOLDOUT', ORDER_VALUE_AUD, 0)) AS H_REVENUE,
         SUM(IFF(EVENT_TYPE = 'CONVERT' AND GROUP_CODE = 'TREATED', MARGIN_AUD, 0)) AS T_MARGIN,
         SUM(IFF(EVENT_TYPE = 'CONVERT' AND GROUP_CODE = 'HOLDOUT', MARGIN_AUD, 0)) AS H_MARGIN,
         SUM(COALESCE(OFFER_COST_AUD, 0)) AS OFFER_COST,
         SUM(COALESCE(SEND_COST_AUD, 0)) AS SEND_COST,
         COUNT_IF(EVENT_TYPE = 'SEND') AS SENDS, COUNT_IF(EVENT_TYPE = 'DELIVER') AS DELIVERED,
         COUNT_IF(EVENT_TYPE = 'BOUNCE') AS BOUNCES,
         COUNT(DISTINCT IFF(EVENT_TYPE = 'OPEN', CUSTOMER_KEY, NULL)) AS OPENERS,
         COUNT(DISTINCT IFF(EVENT_TYPE = 'CLICK', CUSTOMER_KEY, NULL)) AS CLICKERS,
         COUNT_IF(EVENT_TYPE = 'UNSUBSCRIBE') AS UNSUBS, COUNT_IF(EVENT_TYPE = 'COMPLAINT') AS COMPLAINTS,
         MAX(EVENT_DATE) AS LAST_EVENT, MAX(PROVENANCE) AS EVENT_PROVENANCE
  FROM ${S}.CAMPAIGN_EVENT GROUP BY CAMPAIGN_ID
)
SELECT c.CAMPAIGN_ID, c.NAME, c.STATUS, c.OBJECTIVE, c.START_DATE, c.END_DATE, c.SIMULATED_THROUGH, c.BUDGET_AUD,
       c.CHANNELS, c.PROMOTED_CATEGORY, c.PROMOTED_CLASS, c.PROMOTED_BRAND, c.OFFER_ID, c.PROVENANCE, c.HOLDOUT_PCT,
       COALESCE(m.TREATED_N, 0) AS TREATED_N, COALESCE(m.HOLDOUT_N, 0) AS HOLDOUT_N, COALESCE(m.STOCK_CONFLICT_N, 0) AS STOCK_CONFLICT_N,
       COALESCE(m.COLD_N, 0) AS COLD_N,
       COALESCE(e.T_CONV, 0) AS T_CONV, COALESCE(e.H_CONV, 0) AS H_CONV,
       COALESCE(e.T_REVENUE, 0) AS T_REVENUE, COALESCE(e.H_REVENUE, 0) AS H_REVENUE,
       COALESCE(e.T_MARGIN, 0) AS T_MARGIN, COALESCE(e.H_MARGIN, 0) AS H_MARGIN,
       COALESCE(e.OFFER_COST, 0) AS OFFER_COST, COALESCE(e.SEND_COST, 0) AS SEND_COST,
       COALESCE(e.SENDS, 0) AS SENDS, COALESCE(e.DELIVERED, 0) AS DELIVERED, COALESCE(e.BOUNCES, 0) AS BOUNCES,
       COALESCE(e.OPENERS, 0) AS OPENERS, COALESCE(e.CLICKERS, 0) AS CLICKERS, COALESCE(e.UNSUBS, 0) AS UNSUBS,
       COALESCE(e.COMPLAINTS, 0) AS COMPLAINTS, 0 AS REPLIES, e.LAST_EVENT, e.EVENT_PROVENANCE
FROM ${S}.CAMPAIGN c
LEFT JOIN m ON m.CAMPAIGN_ID = c.CAMPAIGN_ID
LEFT JOIN e ON e.CAMPAIGN_ID = c.CAMPAIGN_ID
ORDER BY COALESCE(c.START_DATE, '2099-01-01'::DATE) DESC, c.CAMPAIGN_ID`;

