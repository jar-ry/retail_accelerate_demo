/** Lift by every dimension the investigator and the learnings read (od_43's
 *  VW_MEMBER_DIM). Variant is left out: a holdout gets no variant, so variants
 *  are compared treated vs treated (SQL_VARIANTS_AB). */
export const SQL_LIFT_BY = `
SELECT DIM, COALESCE(VAL, 'Unknown') AS VAL,
       COUNT_IF(GROUP_CODE = 'TREATED') AS TN, COUNT_IF(GROUP_CODE = 'TREATED' AND CONVERTED) AS TC,
       COUNT_IF(GROUP_CODE = 'HOLDOUT') AS HN, COUNT_IF(GROUP_CODE = 'HOLDOUT' AND CONVERTED) AS HC
FROM ${S}.VW_MEMBER_DIM WHERE CAMPAIGN_ID = ? GROUP BY 1, 2 ORDER BY 1, 2`;

export const SQL_VARIANTS_AB = `
WITH conv AS (
  SELECT DISTINCT CUSTOMER_KEY FROM ${S}.CAMPAIGN_EVENT WHERE CAMPAIGN_ID = ? AND EVENT_TYPE = 'CONVERT'
)
SELECT am.VARIANT_CODE, COUNT(*) AS N, COUNT(cv.CUSTOMER_KEY) AS CONV
FROM ${S}.AUDIENCE_MEMBER am LEFT JOIN conv cv ON cv.CUSTOMER_KEY = am.CUSTOMER_KEY
WHERE am.CAMPAIGN_ID = ? AND am.GROUP_CODE = 'TREATED' AND am.VARIANT_CODE IS NOT NULL
GROUP BY 1 ORDER BY 1`;

/** Cumulative conversion rate by day for each arm. */
export const SQL_DAILY = `
WITH first_conv AS (
  SELECT CUSTOMER_KEY, GROUP_CODE, MIN(EVENT_DATE) AS D FROM ${S}.CAMPAIGN_EVENT
  WHERE CAMPAIGN_ID = ? AND EVENT_TYPE = 'CONVERT' GROUP BY 1, 2
), n AS (
  SELECT GROUP_CODE, COUNT(*) AS N FROM ${S}.AUDIENCE_MEMBER WHERE CAMPAIGN_ID = ? GROUP BY 1
), daily AS (
  SELECT D, GROUP_CODE, COUNT(*) AS CONV FROM first_conv GROUP BY 1, 2
)
SELECT d.D AS EVENT_DATE, d.GROUP_CODE,
       SUM(d.CONV) OVER (PARTITION BY d.GROUP_CODE ORDER BY d.D) / MAX(n.N) OVER (PARTITION BY d.GROUP_CODE) AS CUM_RATE
FROM daily d JOIN n ON n.GROUP_CODE = d.GROUP_CODE
ORDER BY 1, 2`;

