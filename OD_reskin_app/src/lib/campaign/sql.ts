/** Treated members also contacted by another campaign within 14 days before. */
export const SQL_OVERLAP = `
WITH me AS (SELECT START_DATE FROM ${S}.CAMPAIGN WHERE CAMPAIGN_ID = ?)
SELECT c2.CAMPAIGN_ID, c2.NAME, c2.START_DATE, COUNT(*) AS SHARED_MEMBERS
FROM ${S}.AUDIENCE_MEMBER a1
JOIN ${S}.AUDIENCE_MEMBER a2 ON a2.CUSTOMER_KEY = a1.CUSTOMER_KEY AND a2.CAMPAIGN_ID <> a1.CAMPAIGN_ID AND a2.GROUP_CODE = 'TREATED'
JOIN ${S}.CAMPAIGN c2 ON c2.CAMPAIGN_ID = a2.CAMPAIGN_ID
CROSS JOIN me
WHERE a1.CAMPAIGN_ID = ? AND a1.GROUP_CODE = 'TREATED'
  AND c2.START_DATE BETWEEN DATEADD('day', -14, me.START_DATE) AND me.START_DATE
GROUP BY 1, 2, 3 ORDER BY 4 DESC`;

