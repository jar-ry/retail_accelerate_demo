// ─── Uplift: cells learned from every campaign with a holdout ────────────────
// The transparent cell-based uplift: lift observed in past campaigns for members
// on the same track in the same need state. Campaigns launched in this app are
// left out, so the model is learned from history only.
export const SQL_UPLIFT_CELLS = `
WITH conv AS (
  SELECT DISTINCT CAMPAIGN_ID, CUSTOMER_KEY FROM ${S}.CAMPAIGN_EVENT WHERE EVENT_TYPE = 'CONVERT' AND PROVENANCE <> 'SIMULATED'
)
SELECT am.TRACK, am.NEED_STATE,
       COUNT_IF(am.GROUP_CODE = 'TREATED') AS TN, COUNT_IF(am.GROUP_CODE = 'TREATED' AND cv.CUSTOMER_KEY IS NOT NULL) AS TC,
       COUNT_IF(am.GROUP_CODE = 'HOLDOUT') AS HN, COUNT_IF(am.GROUP_CODE = 'HOLDOUT' AND cv.CUSTOMER_KEY IS NOT NULL) AS HC
FROM ${S}.AUDIENCE_MEMBER am
JOIN ${S}.CAMPAIGN c ON c.CAMPAIGN_ID = am.CAMPAIGN_ID AND c.PROVENANCE <> 'APP'
LEFT JOIN conv cv ON cv.CAMPAIGN_ID = am.CAMPAIGN_ID AND cv.CUSTOMER_KEY = am.CUSTOMER_KEY
WHERE c.STATUS IN ('MEASURED', 'COMPLETED', 'PAUSED', 'LIVE')
GROUP BY 1, 2`;

/** Lift by channel across the history, for the optimiser's channel factors. */
export const SQL_CHANNEL_LIFT = `
WITH conv AS (
  SELECT DISTINCT CAMPAIGN_ID, CUSTOMER_KEY FROM ${S}.CAMPAIGN_EVENT WHERE EVENT_TYPE = 'CONVERT' AND PROVENANCE <> 'SIMULATED'
)
SELECT am.CHANNEL_CODE,
       COUNT_IF(am.GROUP_CODE = 'TREATED') AS TN, COUNT_IF(am.GROUP_CODE = 'TREATED' AND cv.CUSTOMER_KEY IS NOT NULL) AS TC,
       COUNT_IF(am.GROUP_CODE = 'HOLDOUT') AS HN, COUNT_IF(am.GROUP_CODE = 'HOLDOUT' AND cv.CUSTOMER_KEY IS NOT NULL) AS HC
FROM ${S}.AUDIENCE_MEMBER am
JOIN ${S}.CAMPAIGN c ON c.CAMPAIGN_ID = am.CAMPAIGN_ID AND c.PROVENANCE <> 'APP'
LEFT JOIN conv cv ON cv.CAMPAIGN_ID = am.CAMPAIGN_ID AND cv.CUSTOMER_KEY = am.CUSTOMER_KEY
WHERE c.STATUS IN ('MEASURED', 'COMPLETED', 'PAUSED', 'LIVE') AND am.CHANNEL_CODE IS NOT NULL
GROUP BY 1`;

